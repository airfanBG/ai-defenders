// Напомняне за анкетата: личен линк за всеки участник, за да знаем кой вече е попълнил.
import { sha256, hex } from "./util.js";

// Ключът зависи от имейла и паролата на админа, затова не може да се познае отвън.
export async function surveyRef(env, email) {
  return hex(await sha256("fbref:" + String(email).toLowerCase().trim() + ":" + (env.ADMIN_PASSWORD || ""))).slice(0, 16);
}

